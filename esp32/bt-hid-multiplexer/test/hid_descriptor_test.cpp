// Host-side test of main/hid_descriptor.cpp: finding the keyboard, mouse, consumer control and LED
// reports, the Input Mode and the finger layout of precision touchpads in real and made-up HID report
// descriptors, and reading keyboard, consumer control and touchpad reports by the layout found.
#include <stdio.h>
#include <string.h>
#include "hid_descriptor.h"

static int g_failures = 0;
#define CHECK(cond) do { if (!(cond)) { printf("FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond); g_failures++; } } while (0)

static HidDescriptorInfo parse(const uint8_t *desc, uint16_t len) {
    HidDescriptorInfo info;
    memset(&info, 0xAA, sizeof(info));  // everything must be set by the parser
    hid_descriptor_parse(desc, len, &info);
    return info;
}
#define PARSE(d) parse(d, sizeof(d))

static bool keyboard_is(const HidDescriptorInfo &info, uint8_t id, int8_t mod, uint8_t keys, uint8_t count) {
    return info.has_keyboard && info.keyboard.report_id == id && info.keyboard.modifier_offset == mod &&
           info.keyboard.keys_offset == keys && info.keyboard.key_count == count;
}

static bool mouse_is(const HidDescriptorInfo &info, uint8_t id, uint8_t bits, bool absolute) {
    return info.has_mouse && info.mouse_report_id == id && info.mouse_xy_bits == bits &&
           info.mouse_absolute == absolute;
}

