static void test_ack05() {
    static_assert(sizeof(ACK05) == 286, "the descriptor the device reports is 286 bytes");
    HidDescriptorInfo info = PARSE(ACK05);
    CHECK(keyboard_is(info, 6, 0, 1, 6));
    // The relative mouse, not the absolute pointer that comes first.
    CHECK(mouse_is(info, 1, 16, false));
    CHECK(!info.has_led_output && info.led_report_id == 0);

    // A key report as the device sends it: Left Control + Z.
    const uint8_t report[] = {0x01, 0x1D, 0, 0, 0, 0, 0};
    uint8_t mods = 0xFF, keys[6];
    CHECK(hid_keyboard_report_decode(info.keyboard, report, sizeof(report), &mods, keys));
    CHECK(mods == 0x01 && keys[0] == 0x1D && keys[1] == 0 && keys[5] == 0);
}

// A boot-protocol keyboard (ID 1) with the reserved byte, LEDs, and a mouse on ID 2.
static void test_boot_keyboard_with_leds_and_mouse() {
    const uint8_t desc[] = {
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x01, MODIFIERS, RESERVED,
        0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x75, 0x01, 0x95, 0x05, 0x91, 0x02,  // LEDs
        0x75, 0x03, 0x95, 0x01, 0x91, 0x01,
        0x05, 0x08, 0x91, 0x02,  // a second LED output: the first one is used
        KEYS(6), 0xC0,
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x02, 0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06, 0xC0, 0xC0,
    };
    HidDescriptorInfo info = PARSE(desc);
    CHECK(keyboard_is(info, 1, 0, 2, 6));
    CHECK(info.has_led_output && info.led_report_id == 1);
    CHECK(mouse_is(info, 2, 8, false));

    const uint8_t report[] = {0x02, 0x00, 0x04, 0x05, 0, 0, 0, 0};
    uint8_t mods, keys[6];
    CHECK(hid_keyboard_report_decode(info.keyboard, report, sizeof(report), &mods, keys));
    CHECK(mods == 0x02 && keys[0] == 0x04 && keys[1] == 0x05 && keys[2] == 0);
}

