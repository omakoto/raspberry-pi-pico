static void test_consumer() {
    HidDescriptorInfo info = PARSE(ULANZI_DIAL);
    CHECK(info.has_consumer && info.consumer.report_id == 2 && info.consumer.offset == 0 &&
          info.consumer.size_bits == 16 && info.consumer.count == 1);
    CHECK(keyboard_is(info, 1, 0, 2, 6));
    CHECK(mouse_is(info, 3, 8, false));

    // Volume Up (0x00E9), as the dial sends it; then its release.
    uint16_t usages[4];
    const uint8_t volume_up[] = {0xE9, 0x00};
    CHECK(hid_consumer_report_decode(info.consumer, volume_up, 2, usages, 4) == 1 && usages[0] == 0xE9);
    const uint8_t none[] = {0x00, 0x00};
    CHECK(hid_consumer_report_decode(info.consumer, none, 2, usages, 4) == 0);
    CHECK(hid_consumer_report_decode(info.consumer, volume_up, 1, usages, 4) == -1);

    // An 8-bit array of two usages after a byte of buttons.
    static const uint8_t two_8bit[] = {
        0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0x85, 0x05, 0x09, 0xCD, 0x75, 0x08, 0x95, 0x01, 0x81, 0x02,
        0x19, 0x00, 0x29, 0xFF, 0x75, 0x08, 0x95, 0x02, 0x81, 0x00, 0xC0,
    };
    info = PARSE(two_8bit);
    CHECK(info.has_consumer && info.consumer.report_id == 5 && info.consumer.offset == 1 &&
          info.consumer.size_bits == 8 && info.consumer.count == 2);
    const uint8_t two[] = {0x01, 0xE2, 0xB5};
    CHECK(hid_consumer_report_decode(info.consumer, two, 3, usages, 4) == 2 && usages[0] == 0xE2 &&
          usages[1] == 0xB5);

    // A consumer bitfield (Variable items) is not a usage array.
    static const uint8_t bitfield[] = {
        0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0x85, 0x05, 0x09, 0xE9, 0x09, 0xEA, 0x75, 0x01, 0x95, 0x02,
        0x81, 0x02, 0xC0,
    };
    CHECK(!PARSE(bitfield).has_consumer);
}

