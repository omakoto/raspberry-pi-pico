// Logitech's 12-bit packed X/Y, and an absolute pointer used only when there is no relative one.
static void test_mouse_formats() {
    const uint8_t logitech[] = {
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x02, 0x05, 0x09, 0x19, 0x01, 0x29, 0x10,
        0x75, 0x01, 0x95, 0x10, 0x81, 0x02,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x75, 0x0C, 0x95, 0x02, 0x81, 0x06, 0xC0,
    };
    CHECK(mouse_is(PARSE(logitech), 2, 12, false));

    const uint8_t absolute[] = {
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x03,
        0x09, 0x30, 0x09, 0x31, 0x75, 0x10, 0x95, 0x02, 0x81, 0x02,
        0x09, 0x30, 0x75, 0x10, 0x95, 0x01, 0x81, 0x02,  // a second absolute one: the first is used
        0x09, 0x38, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06,  // relative, but not X/Y
        0x05, 0x02, 0x09, 0x30, 0x81, 0x06,              // relative, X/Y usage, other usage page
        0xC0,
    };
    CHECK(mouse_is(PARSE(absolute), 3, 16, true));

    // X/Y usages only apply to the main item that follows them.
    const uint8_t stale_usage[] = {0x05, 0x01, 0x09, 0x30, 0xA1, 0x00, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06, 0xC0};
    CHECK(!PARSE(stale_usage).has_mouse);
}

// Report IDs may interleave; each keeps its own offsets.
static void test_interleaved_report_ids() {
    const uint8_t desc[] = {
        0x85, 0x04, 0x75, 0x08, 0x95, 0x03, 0x81, 0x02,  // ID 4: 3 bytes
        0x85, 0x05, MODIFIERS,                           // ID 5: modifiers at 0
        0x85, 0x04, 0x75, 0x08, 0x95, 0x01, 0x81, 0x02,  // ID 4: 1 more byte
        0x85, 0x05, KEYS(10),                            // ID 5: keys at 1
    };
    CHECK(keyboard_is(PARSE(desc), 5, 0, 1, 10));
}

static void test_modifier_pairing() {
    // No modifiers at all.
    const uint8_t keys_only[] = {0x85, 0x01, KEYS(6)};
    CHECK(keyboard_is(PARSE(keys_only), 1, -1, 0, 6));

    // Modifiers in another report than the keys.
    const uint8_t other_id[] = {0x85, 0x01, MODIFIERS, 0x85, 0x02, KEYS(6)};
    CHECK(keyboard_is(PARSE(other_id), 2, -1, 0, 6));

    // Variable items that are not the 8 modifier bits (an NKRO bitmap) are not modifiers.
    const uint8_t bitmap[] = {
        0x85, 0x01, 0x05, 0x07, 0x19, 0x04, 0x29, 0x0B, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02, KEYS(6),
    };
    CHECK(keyboard_is(PARSE(bitmap), 1, -1, 1, 6));
}

// Fields that cannot be a usable keycode array.
static void test_not_a_keyboard() {
    // Constant, not on a byte boundary, not 8-bit, empty.
    const uint8_t constant[] = {0x05, 0x07, 0x75, 0x08, 0x95, 0x06, 0x81, 0x01};
    CHECK(!PARSE(constant).has_keyboard);
    const uint8_t unaligned[] = {0x75, 0x01, 0x95, 0x01, 0x81, 0x03, KEYS(6)};
    CHECK(!PARSE(unaligned).has_keyboard);
    const uint8_t wide[] = {0x05, 0x07, 0x75, 0x10, 0x95, 0x06, 0x81, 0x00};
    CHECK(!PARSE(wide).has_keyboard);
    const uint8_t empty[] = {0x05, 0x07, 0x75, 0x08, 0x95, 0x00, 0x81, 0x00};
    CHECK(!PARSE(empty).has_keyboard);
    // Keys beyond byte 255 of the report cannot be addressed.
    const uint8_t far[] = {0x75, 0x08, 0x96, 0xFF, 0x00, 0x81, 0x01, KEYS(6)};
    CHECK(!PARSE(far).has_keyboard);
    // The first keyboard is used.
    const uint8_t two[] = {0x85, 0x01, KEYS(6), 0x85, 0x02, KEYS(6)};
    CHECK(PARSE(two).keyboard.report_id == 1);
}

// The offset table holds 16 report IDs; a keyboard in a later one is not used.
static void test_many_report_ids() {
    const uint8_t keys[] = {KEYS(6)};
    uint8_t desc[17 * 8 + sizeof(keys)];
    uint16_t n = 0;
    for (uint8_t id = 1; id <= 17; id++) {
        const uint8_t item[] = {0x85, id, 0x75, 0x08, 0x95, 0x01, 0x81, 0x02};
        memcpy(desc + n, item, sizeof(item));
        n += sizeof(item);
    }
    memcpy(desc + n, keys, sizeof(keys));  // in ID 17
    n += sizeof(keys);
    CHECK(!parse(desc, n).has_keyboard);
}

static void test_item_forms() {
    // A 4-byte usage minimum (with its usage page in the upper half), a 4-byte report count, and
    // long items, which are skipped.
    const uint8_t desc[] = {
        0xFE, 0x02, 0x10, 0xAA, 0xBB,
        0x85, 0x01, 0x05, 0x07, 0x1B, 0xE0, 0x00, 0x07, 0x00, 0x75, 0x01, 0x97, 0x08, 0x00, 0x00, 0x00, 0x81, 0x02,
        KEYS(6),
    };
    CHECK(keyboard_is(PARSE(desc), 1, 0, 1, 6));

    // Push beyond the 4-deep stack is ignored, and so is Pop on an empty stack.
    const uint8_t stack[] = {
        0xB4,                                      // Pop on empty: nothing
        0x05, 0x07, 0xA4, 0xA4, 0xA4, 0xA4,        // 4 pushes of page 7
        0x05, 0x01, 0xA4,                          // a 5th push is dropped
        0xB4,                                      // back to page 7
        0x85, 0x01, 0x75, 0x08, 0x95, 0x06, 0x81, 0x00,
    };
    CHECK(keyboard_is(PARSE(stack), 1, -1, 0, 6));
}

static void test_truncated() {
    HidDescriptorInfo info;
    hid_descriptor_parse(nullptr, 10, &info);
    CHECK(!info.has_keyboard && !info.has_mouse && !info.has_led_output);

    const uint8_t keyboard[] = {0x85, 0x01, KEYS(6)};
    CHECK(!parse(keyboard, sizeof(keyboard) - 1).has_keyboard);  // the Input item's data is cut off
    const uint8_t long_item[] = {0x85, 0x01, KEYS(6), 0xFE};
    CHECK(PARSE(long_item).has_keyboard);
    const uint8_t long_item2[] = {0xFE, 0x05};
    CHECK(!PARSE(long_item2).has_keyboard);
}

static void test_decode() {
    HidKeyboardLayout layout = {6, 0, 1, 10};
    uint8_t mods, keys[6];

    // Empty entries are skipped and only the first 6 keys are used.
    const uint8_t report[] = {0x80, 0, 0x04, 0, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B};
    CHECK(hid_keyboard_report_decode(layout, report, sizeof(report), &mods, keys));
    const uint8_t want[] = {0x04, 0x05, 0x06, 0x07, 0x08, 0x09};
    CHECK(mods == 0x80 && memcmp(keys, want, 6) == 0);

    CHECK(!hid_keyboard_report_decode(layout, report, sizeof(report) - 1, &mods, keys));

    // Without modifiers.
    layout = {1, -1, 0, 2};
    CHECK(hid_keyboard_report_decode(layout, report, 2, &mods, keys));
    CHECK(mods == 0 && keys[0] == 0x80 && keys[1] == 0);

    // The modifier byte must be within the report too.
    layout = {1, 3, 0, 1};
    CHECK(!hid_keyboard_report_decode(layout, report, 3, &mods, keys));
}

