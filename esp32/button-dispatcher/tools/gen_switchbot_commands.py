#!/usr/bin/env python3
"""Generates components/dispatcher_core/src/switchbot_commands.cpp from the Pi project's command tables.

The data lives in pi/button-dispatcher/button_dispatcher/switchbot_commands.py (a plain data module); the
firmware embeds a copy as static const arrays so both implementations offer the same command picker.

Usage:
  python3 tools/gen_switchbot_commands.py [OUTPUT.cpp]

OUTPUT defaults to ../components/dispatcher_core/src/switchbot_commands.cpp relative to this script.
Run it again whenever switchbot_commands.py changes, and commit the result.
"""

from __future__ import annotations

import importlib.util
import os
import sys
from typing import Sequence

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.normpath(os.path.join(
    HERE, "..", "..", "..", "pi", "button-dispatcher", "button_dispatcher", "switchbot_commands.py"))
DEFAULT_OUTPUT = os.path.normpath(os.path.join(
    HERE, "..", "components", "dispatcher_core", "src", "switchbot_commands.cpp"))

HEX = set("0123456789abcdefABCDEF")


def load_source():
    spec = importlib.util.spec_from_file_location("switchbot_commands_source", SOURCE)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def cpp_string(text: str) -> str:
    """A C++ string literal using only ASCII; non-ASCII bytes become \\xNN escapes."""
    out = []
    after_hex_escape = False
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if byte >= 0x80 or byte < 0x20 or byte == 0x7F:
            named = {10: "\\n", 13: "\\r", 9: "\\t"}.get(byte)
            if named:
                out.append(named)
                after_hex_escape = False
            else:
                out.append("\\x%02x" % byte)
                after_hex_escape = True
            continue
        if after_hex_escape and ch in HEX:
            # Close and reopen the literal so the digit is not read as part of the escape.
            out.append('" "')
        after_hex_escape = False
        if ch == "\\" or ch == '"':
            out.append("\\" + ch)
        elif ch == "?":
            out.append("\\?")  # avoids accidental trigraphs
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def emit_table(lines: list[str], name: str, rows: Sequence[tuple[str, str, str]], exported: bool = False) -> None:
    # Exported names were declared extern in the header, which gives them external linkage.
    lines.append(f"{'const' if exported else 'static const'} CommandEntry {name}[] = {{")
    for command, parameter, description in rows:
        lines.append(f"    {{{cpp_string(command)}, {cpp_string(parameter)}, {cpp_string(description)}}},")
    lines.append("};")
    lines.append("")


def emit_group(lines: list[str], prefix: str, array: str, count: str, tables: dict[str, list]) -> None:
    names = sorted(tables, key=lambda n: n.encode("utf-8"))
    for i, type_name in enumerate(names):
        if tables[type_name]:
            emit_table(lines, f"{prefix}{i}", tables[type_name])
    lines.append(f"const CommandTable {array}[] = {{")
    for i, type_name in enumerate(names):
        rows = tables[type_name]
        if rows:
            lines.append(f"    {{{cpp_string(type_name)}, {prefix}{i}, {len(rows)}}},")
        else:
            lines.append(f"    {{{cpp_string(type_name)}, nullptr, 0}},")
    lines.append("};")
    lines.append(f"const size_t {count} = {len(names)};")
    lines.append("")


def generate() -> str:
    source = load_source()
    lines = [
        "// GENERATED by tools/gen_switchbot_commands.py from",
        "// pi/button-dispatcher/button_dispatcher/switchbot_commands.py. Do not edit by hand: change the",
        "// Python table and run the script again.",
        "",
        '#include "switchbot_commands.hpp"',
        "",
        "namespace dispatcher {",
        "namespace generated {",
        "",
    ]
    emit_group(lines, "kDeviceRows", "kDeviceCommandTables", "kDeviceCommandTableCount", source.DEVICE_COMMANDS)
    emit_group(lines, "kIrRows", "kIrCommandTables", "kIrCommandTableCount", source.IR_COMMANDS)
    emit_table(lines, "kIrCommonCommands", source.IR_COMMON_COMMANDS, exported=True)
    lines.append(f"const size_t kIrCommonCommandCount = {len(source.IR_COMMON_COMMANDS)};")
    lines.append("")
    lines.append("}  // namespace generated")
    lines.append("}  // namespace dispatcher")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) > 2 or (len(argv) == 2 and argv[1] in ("-h", "--help")):
        print(__doc__)
        return 0 if len(argv) == 2 else 2
    output = argv[1] if len(argv) == 2 else DEFAULT_OUTPUT
    text = generate()
    with open(output, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
